        /// <param name="segments">每个 patch 单方向的细分数（原程序由 GLAUX 内部决定，通常 8~12）。</param>
        /// <param name="fitLid">是否施加壶盖 1.077 的贴合修正。</param>
        public static Mesh Build(int segments = 12, bool fitLid = true)
        {
            int seg = Mathf.Max(2, segments);
            int vertsPerPatch = (seg + 1) * (seg + 1);
            int totalVerts = TeapotPatches.Length / 16 * vertsPerPatch;

            Vector3[] vertices = new Vector3[totalVerts];
            Vector3[] normals = new Vector3[totalVerts];
            Vector2[] uvs = new Vector2[totalVerts];
            List<int> triangles = new List<int>(TeapotPatches.Length / 16 * seg * seg * 6);

            // 每个 patch 的 4×4 控制点（数据空间）
            Vector3[,] ctrl = new Vector3[4, 4];

            // 基函数与导数缓存（在循环外分配，避免每个顶点都产生垃圾对象）
            float[] bs = new float[4];
            float[] ds = new float[4];
            float[] bt = new float[4];
            float[] dt = new float[4];

            int vCursor = 0;

            for (int patch = 0; patch < TeapotPatches.Length / 16; patch++)
            {
                int baseIdx = patch * 16;

                // ── 取出 16 个控制点 ──────────────────────────────
                // 行 r 对应参数 s，列 c 对应参数 t
                for (int r = 0; r < 4; r++)
                {
                    for (int c = 0; c < 4; c++)
                    {
                        int vi = TeapotPatches[baseIdx + r * 4 + c];
                        float px = TeapotVertices[vi * 3 + 0];
                        float py = TeapotVertices[vi * 3 + 1];
                        float pz = TeapotVertices[vi * 3 + 2];

                        // 壶盖贴合修正：只放大 X/Y，不动 Z（保持总高不变）
                        bool isLid = fitLid && patch >= 20 && patch <= 27;
                        if (isLid)
                        {
                            px *= LidFitScale;
                            py *= LidFitScale;
                        }

                        ctrl[r, c] = new Vector3(px, py, pz);
                    }
                }

                int patchVertBase = vCursor;

                // ── 对 (s, t) 网格逐点求值 ────────────────────────
                for (int i = 0; i <= seg; i++)
                {
                    float s = (float)i / seg;
                    Basis(s, bs);              // s 方向的位置基函数
                    BasisDerivative(s, ds);    // s 方向的一阶导基函数

                    for (int j = 0; j <= seg; j++)
                    {
                        float t = (float)j / seg;
                        Basis(t, bt);
                        BasisDerivative(t, dt);

                        Vector3 pos = Vector3.zero;
                        Vector3 dPosDs = Vector3.zero;
                        Vector3 dPosDt = Vector3.zero;

                        for (int r = 0; r < 4; r++)
                        {
                            for (int c = 0; c < 4; c++)
                            {
                                Vector3 cp = ctrl[r, c];
                                pos     += bs[r] * bt[c] * cp;
                                dPosDs  += ds[r] * bt[c] * cp;
                                dPosDt  += bs[r] * dt[c] * cp;
                            }
                        }

                        // 法线 = ∂P/∂s × ∂P/∂t（在数据空间里算，指向壶体外侧）
                        Vector3 nrm = Vector3.Cross(dPosDs, dPosDt);
                        if (nrm.sqrMagnitude < 1e-12f)
                        {
                            // 退化点（壶底中心 pos.z≈0、壶盖顶点 pos.z≈3.15）：
                            // 偏导为零，法线取不到，用「朝壶体外侧」兜底
                            nrm = new Vector3(0f, 0f, pos.z < HalfHeight ? -1f : 1f);
                        }
                        nrm.Normalize();

                        vertices[vCursor] = DataToUnity(pos);
                        normals[vCursor] = DataNormalToUnity(nrm);
                        uvs[vCursor] = new Vector2(t, s);
                        vCursor++;
                    }
                }

                // ── 三角形索引 ────────────────────────────────────
                // 顶点顺序与法线方向一致：(P, P+∂s, P+∂t)
                // 注意：材质会把 Cull 关掉（双面渲染），这与原程序一致
                // （OpenGL 默认不开启 GL_CULL_FACE），同时也让绕序不影响可见性。
                for (int i = 0; i < seg; i++)
                {
                    for (int j = 0; j < seg; j++)
                    {
                        int a = patchVertBase + i * (seg + 1) + j;
                        int b = patchVertBase + (i + 1) * (seg + 1) + j;
                        int c = patchVertBase + i * (seg + 1) + (j + 1);
                        int d = patchVertBase + (i + 1) * (seg + 1) + (j + 1);

                        triangles.Add(a); triangles.Add(b); triangles.Add(c);
                        triangles.Add(b); triangles.Add(d); triangles.Add(c);
                    }
                }
            }

            Mesh mesh = new Mesh();
            mesh.name = "UtahTeapot";

            if (totalVerts > 65000)
            {
                // 顶点数超过 16 位索引上限时切换为 32 位索引
                mesh.indexFormat = UnityEngine.Rendering.IndexFormat.UInt32;
            }

            mesh.vertices = vertices;
            mesh.normals = normals;
            mesh.uv = uvs;
            mesh.SetTriangles(triangles, 0);
            mesh.RecalculateBounds();

            return mesh;
        }

        // =================================================================
        // 4. 三次 Bernstein 基函数及其导数
        //    B0 = (1-u)^3        B1 = 3u(1-u)^2     B2 = 3u^2(1-u)     B3 = u^3
        // =================================================================

        static void Basis(float u, float[] b)
        {
            float iu = 1f - u;
            b[0] = iu * iu * iu;
            b[1] = 3f * u * iu * iu;
            b[2] = 3f * u * u * iu;
            b[3] = u * u * u;
        }

        static void BasisDerivative(float u, float[] d)
        {
            float iu = 1f - u;
            d[0] = -3f * iu * iu;
            d[1] = 3f * iu * (1f - 3f * u);   // = 3(1-u)^2 - 6u(1-u)
            d[2] = 3f * u * (2f - 3f * u);    // = 6u - 9u^2
            d[3] = 3f * u * u;
        }

        // =================================================================
        // 5. 数据空间（Z 向上）→ Unity 空间（Y 向上）
        // =================================================================

        /// <summary>绕 X 轴 -90° 的旋转 + 垂直居中：纯旋转，不改变手性。</summary>
        public static Vector3 DataToUnity(Vector3 data)
        {
            return new Vector3(data.x, data.z - HalfHeight, -data.y);
        }

        /// <summary>法线只做旋转分量（不平移）。</summary>
        public static Vector3 DataNormalToUnity(Vector3 n)
        {
            Vector3 v = new Vector3(n.x, n.z, -n.y);
            v.Normalize();
            return v;
        }
    }
